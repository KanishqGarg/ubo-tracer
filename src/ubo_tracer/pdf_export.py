"""PDF generation utility for compliance reports."""

from __future__ import annotations
import io
from typing import List, Dict, Any
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors


def generate_pdf_report(
    target_name: str,
    target_id: str,
    threshold: float,
    results: List[Dict[str, Any]],
    reviewer_name: str = "Compliance Officer",
) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
    styles = getSampleStyleSheet()
    story = []

    # Title
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=18,
        leading=22,
        textColor=colors.HexColor('#0f172a'),
    )
    story.append(Paragraph(f"UBO Investigation Report: {target_name}", title_style))
    story.append(Spacer(1, 10))

    # Mandatory Legal Disclaimer
    disclaimer_style = ParagraphStyle(
        'Disclaimer',
        parent=styles['Normal'],
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#b45309'),
        backColor=colors.HexColor('#fef3c7'),
        borderPadding=6,
    )
    story.append(Paragraph(
        "<b>DECISION SUPPORT ONLY:</b> This report is generated by an automated compliance system. "
        "A qualified compliance officer remains legally accountable for final UBO determinations.",
        disclaimer_style
    ))
    story.append(Spacer(1, 15))

    # Meta info
    meta_style = ParagraphStyle('Meta', parent=styles['Normal'], fontSize=10, leading=14)
    story.append(Paragraph(f"<b>Target Entity ID:</b> {target_id} &nbsp;&nbsp;|&nbsp;&nbsp; <b>Threshold:</b> &gt; {threshold}%", meta_style))
    story.append(Spacer(1, 15))

    # Table of Results
    table_data = [["Owner Name", "Type", "Ownership %", "Status", "Review Flag"]]
    for r in results:
        p_min = r.get("effective_percentage_min", 0.0)
        p_max = r.get("effective_percentage_max", p_min)
        pct_str = f"{p_min:.2f}%" if p_min == p_max else f"{p_min:.2f}% - {p_max:.2f}%"
        table_data.append([
            r.get("owner_name", "Unknown"),
            r.get("owner_type", "unknown"),
            pct_str,
            r.get("status", "UNKNOWN"),
            "YES" if r.get("requires_human_review") else "NO",
        ])

    table = Table(table_data, colWidths=[160, 80, 110, 90, 80])
    table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1e293b')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 10),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 6),
        ('BACKGROUND', (0, 1), (-1, -1), colors.HexColor('#f8fafc')),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
        ('FONTNAME', (0, 1), (-1, -1), 'Helvetica'),
        ('FONTSIZE', (0, 1), (-1, -1), 9),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f8fafc')]),
    ]))
    story.append(table)
    story.append(Spacer(1, 25))

    # Reviewer Sign-off Box
    signoff_style = ParagraphStyle(
        'Signoff',
        parent=styles['Normal'],
        fontSize=10,
        leading=16,
        borderPadding=10,
        borderColor=colors.HexColor('#94a3b8'),
        borderWidth=1,
    )
    story.append(Paragraph(
        f"<b>Reviewer Sign-off:</b><br/>"
        f"Assigned Officer: __________________________ &nbsp;&nbsp;&nbsp;&nbsp; Date: _______________<br/>"
        f"Determination: [  ] Approved &nbsp;&nbsp;&nbsp;&nbsp; [  ] Rejected &nbsp;&nbsp;&nbsp;&nbsp; [  ] Further Inquiry Needed<br/>"
        f"Signature: ________________________________________________",
        signoff_style
    ))

    doc.build(story)
    return buffer.getvalue()

